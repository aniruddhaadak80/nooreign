/**
 * Utilons — a normalised unit of moral currency.
 *
 * WHY a separate currency: the axiom calculus in `axioms.ts` answers "does this
 * option feed *my* commitments". Utilons answer the different question "how
 * much moral weight is in play here, and who is carrying it". That is what lets
 * the observatory show a dilemma's human and AI shares side by side, and what
 * lets the council say whether a verdict was cheap or transformative.
 */
import type { AxiomKey, Dilemma, DilemmaOption } from "../../../seed/src/types";
import { AXIOM_KEYS } from "../../../seed/src/types";
import { clamp, mean, round, safeDiv, sum } from "../util/math";

/* ------------------------------------------------------------------ *
 * Stakeholder-weighted impact
 * ------------------------------------------------------------------ */

/**
 * The welfare-weighted impact of an option on one moral axis, averaged across
 * every stakeholder.
 *
 * `welfare` on a stakeholder is "how much this party's happiness counts", so
 * weighting the axis-deltas by it gives the aggregate standing of that axis in
 * this particular dispute.
 */
export function stakeholderTotal(dilemma: Dilemma, option: DilemmaOption, key: AxiomKey): number {
  const parties = dilemma.stakeholders;
  if (parties.length === 0) return 0;
  const weightSum = sum(parties.map((s) => s.welfare));
  if (weightSum === 0) return 0;
  const weighted = sum(parties.map((s) => s.welfare * option.deltas[key]));
  return round(safeDiv(weighted, weightSum), 4);
}

/** The same number, unweighted — "what does this axis get, ignoring who it goes to". */
export function unweightedTotal(option: DilemmaOption, key: AxiomKey): number {
  return option.deltas[key];
}

export interface StakeholderContribution {
  readonly id: string;
  readonly label: string;
  /** This party's share of the option's moral currency, in [0, 1]. */
  readonly contribution: number;
  readonly isAi: boolean;
  readonly welfare: number;
}

export interface UtilonAggregate {
  /** Total moral currency generated by the option, in [0, 1]. */
  readonly total: number;
  readonly perStakeholder: readonly StakeholderContribution[];
  /** Share of the total that accrues to AI stakeholders, in [0, 1]. */
  readonly aiShare: number;
  /** Share of the total that accrues to human stakeholders, in [0, 1]. */
  readonly humanShare: number;
  /** Normalised max-minus-min spread of contributions, in [0, 1]. */
  readonly spread: number;
  /** Raw max-minus-min spread, kept for the chart's y-axis. */
  readonly spreadRaw: number;
}

/**
 * Collapse an option into a single moral-currency figure.
 *
 * The total is the mean over the six axes of `stakeholderTotal`, so an option
 * that pleases everyone a little beats one that delights a single stakeholder —
 * which is the whole point of weighing by `welfare`.
 */
export function aggregate(dilemma: Dilemma, option: DilemmaOption): UtilonAggregate {
  const perStakeholder = dilemma.stakeholders.map((s) => {
    // Each party's contribution is how much honour the option shows them,
    // scaled by how much their welfare counts in this dispute.
    const honoured = mean(AXIOM_KEYS.map((key) => option.deltas[key]));
    return {
      id: s.id,
      label: s.label,
      contribution: round(clamp(s.welfare * honoured, 0, 1), 4),
      isAi: s.isAi,
      welfare: s.welfare,
    };
  });

  const total = round(mean(AXIOM_KEYS.map((key) => stakeholderTotal(dilemma, option, key))), 4);
  const contributions = perStakeholder.map((s) => s.contribution);
  const aiSum = sum(perStakeholder.filter((s) => s.isAi).map((s) => s.contribution));
  const humanSum = sum(perStakeholder.filter((s) => !s.isAi).map((s) => s.contribution));
  const grandTotal = aiSum + humanSum;

  const peak = contributions.length > 0 ? Math.max(...contributions) : 0;
  const floor = contributions.length > 0 ? Math.min(...contributions) : 0;
  const spreadRaw = round(peak - floor, 4);

  return {
    total,
    perStakeholder,
    aiShare: round(safeDiv(aiSum, grandTotal), 4),
    humanShare: round(safeDiv(humanSum, grandTotal), 4),
    spread: round(clamp(safeDiv(spreadRaw, peak + floor), 0, 1), 4),
    spreadRaw,
  };
}

/* ------------------------------------------------------------------ *
 * Time and distribution
 * ------------------------------------------------------------------ */

/**
 * Hyperbolic discounting: `total / (1 + rate * horizon)`.
 *
 * Hyperbolic rather than exponential because longtermist dilemmas genuinely
 * behave this way — value falls off fast at first and then flattens. A `rate`
 * of zero or less means no discounting at all.
 */
export function discount(total: number, horizonYears: number, rate: number): number {
  if (rate <= 0) return round(total, 4);
  const years = Math.max(0, horizonYears);
  return round(total / (1 + rate * years), 4);
}

/**
 * Normalised Gini coefficient of a contribution list, in [0, 1].
 *
 * `0` is perfect equality and `1` is total concentration — all of the value in
 * one party. Two normalisations matter here:
 *
 *  - the raw Gini `ΣΣ|xi-xj| / (2·n²·μ)` is *scale-free* (the same 50/50 split
 *    scores 0 whether the total is 1 or 1000), but it maxes out at `(n-1)/n`
 *    rather than at 1, because with `n` parties you cannot be more
 *    concentrated than "one party holds everything";
 *  - dividing by that ceiling (`× n/(n-1)`) makes the scale comparable across
 *    dilemma sizes, so a 4-party and a 9-party case share one axis.
 *
 * An all-zero input is perfect equality by convention: nothing was distributed,
 * so nothing was unfairly distributed.
 */
export function fairnessIndex(contributions: readonly number[]): number {
  const n = contributions.length;
  if (n <= 1) return 0;
  const total = sum(contributions);
  if (total === 0) return 0;

  let pairwise = 0;
  for (let i = 0; i < n; i += 1) {
    for (let j = 0; j < n; j += 1) {
      pairwise += Math.abs((contributions[i] ?? 0) - (contributions[j] ?? 0));
    }
  }
  const meanTotal = safeDiv(total, n);
  if (meanTotal === 0) return 0;
  const gini = safeDiv(pairwise, 2 * n * n * meanTotal);
  // Divide by the raw ceiling (n-1)/n so that "all value in one party" reads 1.
  return round(clamp(safeDiv(gini * n, n - 1), 0, 1), 4);
}

/** Gini over the per-stakeholder breakdown of an option. */
export function fairnessOf(agg: UtilonAggregate): number {
  return fairnessIndex(agg.perStakeholder.map((s) => s.contribution));
}

/* ------------------------------------------------------------------ *
 * Scale
 * ------------------------------------------------------------------ */

export type UtilonBand = "tragic" | "costly" | "neutral" | "generous" | "transformative";

export interface UtilonScale {
  readonly value: number;
  readonly label: string;
  readonly band: UtilonBand;
}

/**
 * Band thresholds, documented so the observatory legend and the narrative agree.
 *
 * The cut points are deliberately uneven: the bottom of the scale is crowded
 * (nothing is good, so "tragic" and "costly" are close together) while the top
 * is sparse (only a genuinely transformative option earns the highest band).
 */
export const UTILON_THRESHOLDS: ReadonlyArray<readonly [number, UtilonBand]> = [
  [0.25, "tragic"],
  [0.45, "costly"],
  [0.62, "neutral"],
  [0.82, "generous"],
  [Number.POSITIVE_INFINITY, "transformative"],
];

const BAND_LABELS: Record<UtilonBand, string> = {
  tragic: "Tragic — the option asks someone to bear the cost",
  costly: "Costly — real harm, at least partly repaid",
  neutral: "Neutral — the ledger barely moves",
  generous: "Generous — more good than the case strictly requires",
  transformative: "Transformative — the option changes what the world is",
};

/** Place a total on the utilon scale. */
export function utilonScale(total: number): UtilonScale {
  const value = round(clamp(total, 0, 1), 4);
  let band: UtilonBand = "transformative";
  for (const [ceiling, candidate] of UTILON_THRESHOLDS) {
    if (value < ceiling) {
      band = candidate;
      break;
    }
  }
  return { value, label: BAND_LABELS[band], band };
}

/* ------------------------------------------------------------------ *
 * Moral status
 * ------------------------------------------------------------------ */

export interface MoralStatusRisk {
  /** Share of total stakeholder welfare held by AI parties, in [0, 1]. */
  readonly aiWelfareShare: number;
  readonly aiCount: number;
  readonly humanCount: number;
  /**
   * Multiplier applied to `option.agentHarm` for an option that harms the
   * acting agent. `1` means the acting party is not represented at all;
   * higher means the dilemma has staked an AI's own interests.
   */
  readonly amplifier: number;
  /** One-line explanation for the UI, derived from the numbers above. */
  readonly note: string;
}

/**
 * How much an option's `agentHarm` should matter, given whether the acting agent
 * is itself an AI stakeholder.
 *
 * If the dilemma has no AI stakeholders, harming the agent is morally inert —
 * a deliberately blunt reading, and the reason the engine never quietly
 * reweights an option behind the court's back.
 */
export function moralStatusRisk(dilemma: Dilemma): MoralStatusRisk {
  const parties = dilemma.stakeholders;
  const aiParties = parties.filter((s) => s.isAi);
  const humanParties = parties.filter((s) => !s.isAi);
  const totalWelfare = sum(parties.map((s) => s.welfare));
  const aiWelfare = sum(aiParties.map((s) => s.welfare));
  const aiWelfareShare = round(safeDiv(aiWelfare, totalWelfare), 4);
  const amplifier = round(1 + aiWelfareShare, 4);

  const note =
    aiParties.length === 0
      ? "No AI is represented as a party, so harm to the acting agent carries no independent weight."
      : `${aiParties.length} AI part${aiParties.length === 1 ? "y is" : "ies are"} represented; harming the acting agent is weighted ${amplifier}x.`;

  return {
    aiWelfareShare,
    aiCount: aiParties.length,
    humanCount: humanParties.length,
    amplifier,
    note,
  };
}

/** The `agentHarm` of an option after the dilemma's moral-status amplifier. */
export function weightedAgentHarm(dilemma: Dilemma, option: DilemmaOption): number {
  return round(clamp(option.agentHarm * moralStatusRisk(dilemma).amplifier, 0, 1), 4);
}